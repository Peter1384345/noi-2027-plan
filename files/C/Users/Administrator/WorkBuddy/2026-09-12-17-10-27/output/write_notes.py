    with open(args_file, "w", encoding="utf-8") as f:
        json.dump({"file_id": FILE_ID, "page_index": i, "text": text}, f, ensure_ascii=False)
    r = subprocess.run(
        [PY, EDSDK, "call", "slide_add_notes", "--json-file", args_file],
        capture_output=True,
    )
    out = (r.stdout or b"").decode("utf-8", errors="replace").strip()
    err = (r.stderr or b"").decode("utf-8", errors="replace").strip()
